#include "frame_filter.h"
#include <algorithm>
#include <cassert>
#include <cstdio>
#include <thread>
#include <vector>

namespace {
void edges() {
    const uint32_t red = 0xff0000ffu, white = 0xffffffffu;
    const uint32_t source[] = {white, white, red, white, red, red, red, red, red};
    for (unsigned scale = 2; scale <= 4; scale++) {
        const unsigned side = 3 * scale, stride = side + 3;
        std::vector<uint32_t> out(side * stride, 0);
        assert(arcade::hqxFits(3, 3, scale));
        assert(arcade::scaleHqx(source, 3, 3, 12, scale, out.data(), stride * 4));
        assert(out[0] == white && out[side - 1] == red);
        bool interpolated = false;
        for (unsigned y = 0; y < side; y++) {
            for (unsigned x = 0; x < side; x++) {
                auto p = out[y * stride + x];
                assert((p & 0xff0000ffu) == red);  // preserve alpha, red and channel order
                interpolated |= p != white && p != red;
            }
            assert(out[y * stride + side] == 0);
        }
        assert(interpolated);
    }
    uint32_t out[6 * 6];
    assert(!arcade::scaleHqx(source, 3, 3, 8, 2, out, 24));
    assert(!arcade::scaleHqx(source, 3, 3, 13, 2, out, 24));
    assert(!arcade::scaleHqx(source, 3, 3, 12, 2, out, 23));
    assert(!arcade::hqxFits(1024, 240, 4));
    assert(!arcade::hqxFits(0, 240, 2));
    assert(!arcade::hqxFits(512, 512, 4));
}

void referencePixels(unsigned variation) {
    // Pixel checksums generated by the 0.5.0 scaler, excluding padding.
    const uint64_t reference[2][3] = {
        {UINT64_C(0x7a4c1980f6ae14e2), UINT64_C(0x90e7ec765675e1dd), UINT64_C(0x06d86ada46d22eef)},
        {UINT64_C(0x59f645169da67a71), UINT64_C(0xd19de6e8c931aa8d), UINT64_C(0x985260750644c9b8)},
    };
    constexpr unsigned w = 43, h = 31, srcPitch = w + 4;
    constexpr uint32_t guard = 0xdeadbeefu;
    std::vector<uint32_t> src(srcPitch * h, guard);
    for (unsigned y = 0; y < h; ++y) for (unsigned x = 0; x < w; ++x) {
        uint32_t rgb = (x * 59107u ^ y * 32063u ^ (x + y + variation) * 13577u) & 0xffffff;
        src[y * srcPitch + x] = x % 8 < 4 || y % 8 < 4 ? 0xff000000u | rgb : 0x8089bcd1u;
    }
    const auto original = src;
    for (unsigned f = 2; f <= 4; ++f) {
        const unsigned stride = w * f + 5;
        std::vector<uint32_t> out(stride * h * f, guard);
        assert(arcade::scaleHqx(src.data(), w, h, srcPitch * 4, f, out.data(), stride * 4));
        uint64_t value = UINT64_C(14695981039346656037);
        for (unsigned y = 0; y < h * f; ++y) {
            for (unsigned x = 0; x < w * f; ++x)
                value = (value ^ out[y * stride + x]) * UINT64_C(1099511628211);
            const auto first = out.begin() + y * stride + w * f;
            assert(std::all_of(first, first + 5, [](uint32_t p) { return p == guard; }));
        }
        assert(value == reference[variation][f - 2]);
    }
    assert(src == original);
}
} // namespace

int main() {
    edges();
    std::thread other(referencePixels, 1); // Scratch and cache are independent of another presenter.
    referencePixels(0);
    other.join();
    std::puts("HQ2x/HQ3x/HQ4x match 0.5.0 pixels with padded snapshots and thread-local scratch.");
}
